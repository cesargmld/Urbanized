export const LANGS = [
  { code: 'es', name: 'ES · Español' },
  { code: 'en', name: 'EN · English' },
];

const LOCALES = { es: 'es-ES', en: 'en-US' };
export const locale = () => LOCALES[lang] ?? 'es-ES';
const known = (code) => LANGS.some((l) => l.code === code);

const saved = (() => {
  try { return localStorage.getItem('ue:lang'); } catch { return null; }
})();
export let lang = known(saved) ? saved : 'en';

export function t(key, vars = {}) {
  let s = DICT[lang]?.[key] ?? DICT.en?.[key] ?? DICT.es?.[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    s = s.replaceAll(`{${k}}`, v);
  }
  return s;
}

const listeners = new Set();
export const onLangChange = (fn) => listeners.add(fn);

export async function applyLang(next = lang) {
  if (!known(next)) next = 'en';
  lang = next;
  try { if (typeof localStorage !== 'undefined') localStorage.setItem('ue:lang', lang); } catch { /* private mode */ }

  if (typeof document !== 'undefined') {
    document.documentElement.lang = lang;
    document.title = t('title');

    // Text content
    document.querySelectorAll('[data-i18n]').forEach((el) => {
      el.textContent = t(el.dataset.i18n);
    });

    // HTML content
    document.querySelectorAll('[data-i18n-html]').forEach((el) => {
      el.innerHTML = t(el.dataset.i18nHtml);
    });

    // Placeholder
    document.querySelectorAll('[data-i18n-ph]').forEach((el) => {
      el.placeholder = t(el.dataset.i18nPh);
    });

    // Aria label
    document.querySelectorAll('[data-i18n-aria]').forEach((el) => {
      el.setAttribute('aria-label', t(el.dataset.i18nAria));
    });

    // Title
    document.querySelectorAll('[data-i18n-title]').forEach((el) => {
      el.title = t(el.dataset.i18nTitle);
    });

    // Tooltip
    document.querySelectorAll('[data-i18n-tooltip]').forEach((el) => {
      el.setAttribute('data-tooltip', t(el.dataset.i18nTooltip));
    });

    // Synchronize language dropdowns
    document.querySelectorAll('.lang-select, .lang-pill').forEach((sel) => {
      sel.value = lang;
    });

    // Synchronize 1-piece language toggle button
    const singleLangBtn = document.getElementById('btn-lang-toggle');
    const singleLangLbl = document.getElementById('lang-current-label');
    if (singleLangLbl) {
      singleLangLbl.textContent = lang.toUpperCase();
    }
    if (typeof window !== 'undefined') {
      window.currentLang = lang;
    }
  }

  listeners.forEach((fn) => {
    try { fn(lang); } catch (e) { console.warn('i18n listener error', e); }
  });
}
if (typeof window !== 'undefined') {
  window.applyLang = applyLang;
}
